def _ov_shape(func, x, T):
    if x < 0.0:
        x = 0.0
    if func == "linear":
        return x
    if func == "sq":
        return x * x
    if func == "sqrt":
        return math.sqrt(x)
    if func == "log":
        return math.log(1.0 + x)
    if func == "hinge":
        if not T or T <= 0:
            return x
        u = x / T
        d = u - 1.0
        return u + _OV_HINGE_GAIN * (d * d if d > 0 else 0.0)
    return x


def _ov_price(item, inv):
    p = _OV_MARKET[item]
    base, T = p["base"], p["T"]
    if inv < _OV_I0:
        amp = p["bt"] * base / _ov_shape(p["bf"], T, T)
        price = base + amp * _ov_shape(p["bf"], _OV_I0 - inv, T)
    else:
        amp = p["at"] * base / _ov_shape(p["af"], T, T)
        price = base - amp * _ov_shape(p["af"], inv - _OV_I0, T)
    v = int(round(price))
    return 1 if v < 1 else v


