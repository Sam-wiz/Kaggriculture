# Survival override -- see NOTES.md. When the morning hires silently fail for
# want of cash the tape keeps running a 12-hand script with one farmer: nothing
# is watered or fed, every crop is a weed within two days, the livestock starves
# and the game ends at a bank of 0. Measured on real ladder replays, this trigger
# fires in exactly the games that ended at zero and in ZERO turns across healthy
# games, so it is inert except where the game is already lost.
