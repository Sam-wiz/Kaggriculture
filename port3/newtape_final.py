def _choose_observed_tail(state, seat=0):
    # policy.cpp::select_route as published 2026-09-03 -- this tape's own selector,
    # which is NOT the one the earlier tape used.
    if state.n_shops >= 1:
        if (state.shops[0] == SHOP_BAKERY and
                float(state.market_inventory[FERTILIZER]) <= 10232.5):
            return True
        if (state.shops[0] == SHOP_PET_CAFE and
                float(state.rival_plant_tiles()) <= 64.5):
            return True
    return False


